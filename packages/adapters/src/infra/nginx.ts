/**
 * Reverse-proxy headers shared by every proxy_pass location.
 *
 * X-Forwarded-Proto carries `$openship_fwd_proto`, not `$scheme` — see
 * {@link FORWARD_VARS}. Every server block generated by `registerRoute` defines
 * that variable, and these headers are only ever emitted inside those blocks.
 */
/**
 * Control characters, excluded from every regex capture and location we generate.
 *
 * A regex location matches the DECODED `$uri`, and `return` copies the capture into the
 * `Location` header verbatim — so `/blog/a%0Db` would plant a bare CR in a response
 * header, the lenient-parser half of response splitting. PCRE's `.` already excludes LF
 * and nginx rejects NUL outright, but CR and the rest of C0 get through, so captures
 * exclude control characters instead of relying on `.`. It matters more for a rewrite,
 * whose capture lands in an UPSTREAM REQUEST LINE rather than a response header.
 *
 * A control character therefore just fails to match and falls through to `location /` —
 * the same thing an encoded LF does today. Printable multi-byte UTF-8 still matches
 * (`/blog/caf%C3%A9` → `/news/café`, which clients re-encode).
 *
 * Applied at EMIT time, not in the compiled `pattern`: that pattern is shared with
 * Openship Cloud's edge, whose matcher takes the documented `(.*)` form and does its
 * own hygiene. This escaping is nginx's business alone.
 */
const CTL = "\\x00-\\x1f\\x7f";

/**
 * `proxy_pass_header X-Accel-Buffering` is load-bearing, not decoration: nginx hides
 * the whole X-Accel-* family from the response it passes downstream, so an upstream's
 * "don't buffer me" instruction is consumed by the FIRST proxy that honours it. A
 * Cloud-fronted `*.opsh.io` host has two hops, and the second one buffered a stream
 * this one had correctly let through — SSE arriving as one blob at close, or not at
 * all (GH-570). Re-exposing the header costs nothing for a response that doesn't set
 * it, which is every response but a stream.
 *
 * Hop 2 is NOT configured from this repo (managed-edge-proxy only hands Cloud a slug
 * and a target), so that it honours the header is inference from nginx's defaults, not
 * something a test here can prove. Confirm it once against a live `*.opsh.io` SSE
 * endpoint. It names one field deliberately: X-Accel-Redirect stays hidden, so a
 * tenant app cannot drive an internal redirect inside Cloud's shared edge.
 */
const PROXY_HEADERS = `proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $openship_fwd_proto;
        proxy_http_version 1.1;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection "upgrade";
        proxy_pass_header X-Accel-Buffering;`;

/**
 * Per-request vars every generated server block opens with.
 *
 * Both exist because a CDN in front of us may terminate TLS and then reach origin
 * on plain :80 (Cloudflare's "Flexible" SSL mode is the common case):
 *
 *   $openship_redirect_https — an unconditional `301 → https` on :80 sends such a
 *     request back to the CDN, which comes back here on :80: an infinite redirect
 *     loop. Only bounce a request that really arrived over HTTP.
 *   $openship_fwd_proto — overwriting the CDN's X-Forwarded-Proto with `$scheme`
 *     tells the app "http" for a request the browser made over https, which breaks
 *     app-generated absolute URLs, secure cookies, and framework HTTPS guards.
 *
 * Built-in variables only, deliberately: an http-level `map` would have to be
 * shipped in the edge's nginx.conf, and a vhost referencing a variable an
 * already-deployed edge doesn't define fails `openresty -t` — which means the
 * reload is refused and registerRoute rolls the route back. This template has to
 * stay valid on an edge running an older image.
 *
 * Only an EXACT "https" is honoured, and the literal `https` is what gets forwarded
 * — never the client's own string. A chained-proxy header is legally a list
 * ("http, https"), and passing that through verbatim confuses frameworks that
 * compare it to "https"; anything unrecognised falls back to `$scheme`.
 *
 * X-Forwarded-Proto is client-spoofable on a directly-exposed box. All a client
 * gains by lying is skipping its OWN redirect (and telling the app its own request
 * was https) — it can't affect anyone else's traffic, and it could simply have
 * used https to begin with.
 */
const FORWARD_VARS = `    set $openship_fwd_proto $scheme;
    set $openship_redirect_https 1;
    if ($http_x_forwarded_proto = "https") {
        set $openship_fwd_proto https;
        set $openship_redirect_https 0;
    }`;

/**
 * Shape revision of the vhosts this build emits.
 *
 * BUMP IT whenever the generated block changes in a way an already-written vhost has to
 * pick up — a new realip block, a new location, a changed forwarded header. It is the only
 * thing that makes such a fix reach a box, because `registerRoute` is the sole writer and
 * only a deploy, a domain save or a Retry calls it: an upgrade alone leaves every existing
 * vhost exactly as the old generator wrote it, indefinitely.
 * {@link NginxProvider.reapplyStoredRoutes} replays anything stamped below this.
 *
 * 1 — server-scope X-Real-IP recovery for Cloud-fronted `*.opsh.io` hosts. Vhosts written
 *     before it log every free-domain visitor as Openship Cloud's edge.
 * 2 — `proxy_pass_header X-Accel-Buffering`, so an upstream's no-buffering instruction
 *     survives the second proxy hop. Vhosts written before it stall SSE behind Cloud's
 *     edge (GH-570).
 */
export const VHOST_GENERATION = 2;

/** Marker line carrying {@link VHOST_GENERATION}, matched by {@link readVhostGeneration}. */
const GENERATION_MARKER = `# openship-vhost-gen: ${VHOST_GENERATION}`;

