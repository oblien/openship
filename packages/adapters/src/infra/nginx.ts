/** Only allow valid domain characters - prevents shell injection. Allows wildcards. */
const DOMAIN_RE = /^(\*\.)?[a-zA-Z0-9]([a-zA-Z0-9.-]*[a-zA-Z0-9])?$/;
function assertValidDomain(domain: string): void {
  if (!DOMAIN_RE.test(domain) || domain.length > 253) {
    throw new Error(`Invalid domain: ${domain}`);
  }
}

/**
 * `proxy_pass`/`root` values are interpolated verbatim into the generated
 * server{} block and — on proxy adopt/takeover — come from PARSING A FOREIGN
 * proxy config (semi-trusted). Reject anything that could break out of the
 * single-token directive and inject arbitrary nginx config. `openresty -t` only
 * catches MALFORMED output, so a well-formed injection would otherwise slip in.
 * Normal deploy targets (`http://127.0.0.1:3000`, `/var/www/app`) contain none
 * of these chars, so this never rejects a legitimate route.
 */
function assertNoNginxInjection(value: string, what: string): void {
  // Quotes are in the set because several sinks here are QUOTED strings (an `if` regex, a
  // `map` match, an `add_header` value): a stray `"` or `'` ends the token early and the
  // rest of the line becomes stray directives, which is an `[emerg]` and — since
  // `openresty -t` is whole-config — a refused reload rather than one bad rule. No current
  // producer can reach it (the compiler rejects them first), which is exactly why the
  // backstop should not have a hole in it.
  if (/[\s;{}#\\'"]/.test(value)) {
    throw new Error(
      `Invalid ${what} (contains characters that could inject nginx config): ${value}`,
    );
  }
}

/**
 * A `$` in an interpolated value expands as an nginx RUNTIME VARIABLE at the sink.
 * `assertNoNginxInjection` cannot cover it, because plenty of what this file emits is
 * legitimately `$host` / `$request_uri` — so the ban is applied per-value, to the ones
 * that come from OUTSIDE (a compiled vercel.json, the API, a route sidecar on disk).
 *
 * The compiler already refuses these, but it is not the only producer of a
 * `RouteConfig`, and the consequences at the sink are severe enough to re-check:
 * `proxy_pass http://$http_x_target` is an open proxy any visitor steers with one
 * request header, and `return 307 https://$arg_next` is an open redirect.
 *
 * `allowCaptures` permits a bare `$1`..`$9`, which a wildcard redirect's destination
 * and a rewrite's upstream path legitimately reference.
 */
function assertNoRuntimeVariable(value: string, what: string, allowCaptures = false): void {
  const residue = allowCaptures ? value.replace(/\$[1-9]/g, "") : value;
  if (residue.includes("$")) {
    throw new Error(`Invalid ${what} (contains an nginx variable reference): ${value}`);
  }
}

function assertValidUpstream(targetUrl: string): void {
  assertNoNginxInjection(targetUrl, "proxy target");
  assertNoRuntimeVariable(targetUrl, "proxy target");
  if (!/^https?:\/\/.+/.test(targetUrl)) {
    throw new Error(`Invalid proxy target (must be http/https URL): ${targetUrl}`);
  }
}

/**
 * Exactly the capture patterns `compileVercelRouting` produces: safe path literals
 * (an escaped `.`) plus the four capture groups. Whitelisted rather than
 * blacklisted because this value lands in a `location ~ …` regex, where
 * `assertNoNginxInjection`'s ban on `\` would reject our own escaped dots while
 * still admitting regex a vercel.json has no business supplying.
 *
 * Deliberately RESTATES the compiler's vocabulary instead of importing it: a route
 * also arrives from the API and from a sidecar on disk, so a guard that derived its
 * rule from the thing it is guarding would approve whatever that thing emitted. The
 * cost is drift, which the "accepts every capture pattern" round-trip test catches.
 */
const REDIRECT_PATTERN_RE = /^\/(?:[A-Za-z0-9_~\-/]|\\\.|\(\.\*\)|\(\.\+\)|\(\[\^\/\][*+]\))*$/;

function assertValidRedirectPattern(pattern: string): void {
  if (!REDIRECT_PATTERN_RE.test(pattern)) {
    throw new Error(`Invalid capture pattern: ${pattern}`);
  }
}

/**
 * A literal path — a redirect's `path`, a header rule's `path`, a proxy location's
 * prefix — now lands inside a REGEX, so it must not carry regex metacharacters.
 *
 * Every metacharacter is rejected EXCEPT `.`, which is legitimate in a path and is
 * escaped by {@link escapeLiteralPath}; that exception is the whole reason the escaper is
 * provably complete. Everything else a path may plausibly contain (percent-encoding, `@`,
 * `,`, `=`) is left alone — a takeover-derived or API-supplied prefix should not fail
 * registration for a character that changes nothing about how the regex matches.
 */
const REGEX_METACHARS = /[*+?^$()[\]|]/;

function assertValidLiteralPath(value: string, what: string): void {
  assertNoNginxInjection(value, what);
  if (!value.startsWith("/") || REGEX_METACHARS.test(value)) {
    throw new Error(`Invalid ${what} (not a plain path): ${value}`);
  }
}

/**
 * Neutralize a literal path for use inside a regex. Written `[.]` rather than `\.` so
 * nothing depends on how nginx unescapes a backslash inside a quoted string — the same
 * choice {@link renderUrlShape} makes. Complete only because
 * {@link assertValidLiteralPath} has already excluded every other metacharacter.
 */
function escapeLiteralPath(value: string): string {
  return value.replace(/\./g, "[.]");
}

/** A redirect's match + destination are interpolated into the vhost; re-check both
 *  here so a route arriving from the API or a sidecar can't inject config either. */
function assertValidRedirect(redirect: RouteRedirect): void {
  if (redirect.pattern !== undefined) assertValidRedirectPattern(redirect.pattern);
  assertValidLiteralPath(redirect.path, "redirect path");
  assertNoNginxInjection(redirect.destination, "redirect destination");
  // The destination lands in a `Location` header; only its own captures may be `$…`.
  assertNoRuntimeVariable(redirect.destination, "redirect destination", true);
}

/** The portable capture groups, hardened for nginx's sink — see {@link CTL}. */
const NGINX_CAPTURE: Record<string, string> = {
  "(.*)": `([^${CTL}]*)`,
  "(.+)": `([^${CTL}]+)`,
  "([^/]+)": `([^/${CTL}]+)`,
  "([^/]*)": `([^/${CTL}]*)`,
};

/**
 * Swap each portable capture for its hardened form. Safe as a blind replace because
 * `REDIRECT_PATTERN_RE` has already established the pattern contains only these.
 *
 * `alsoExclude` adds characters to every capture's excluded set. `renderRedirectRules`
 * passes `?` because it matches `$request_uri`, which carries the query string: a
 * greedy `(.*)` would capture `x?a=1` whole and the emitted redirect would then append
 * the query a second time. A `$uri` sink (the rewrite locations) passes nothing.
 */
function toNginxPattern(pattern: string, alsoExclude = ""): string {
  return pattern.replace(/\(\.[*+]\)|\(\[\^\/\][*+]\)/g, (group) => {
    const hardened = NGINX_CAPTURE[group];
    if (!hardened) return group;
    return alsoExclude ? hardened.replace(`${CTL}]`, `${CTL}${alsoExclude}]`) : hardened;
  });
}

/**
 * An edge-target challenge token becomes a FILENAME, so this is stricter than
 * `assertNoNginxInjection` — that one guards nginx syntax, this one guards the
 * filesystem. A `/` would write outside the challenge dir and `..` would traverse
 * out of it, and neither contains a character nginx would object to.
 *
 * Accepts hex / base64url / dotted tokens, which is every shape Oblien issues.
 */
const CHALLENGE_TOKEN_RE = /^[A-Za-z0-9][A-Za-z0-9._~-]{7,127}$/;

export function assertValidChallengeToken(token: string): void {
  if (!CHALLENGE_TOKEN_RE.test(token) || token.includes("..")) {
    throw new Error(`Invalid edge-target challenge token: ${token}`);
  }
}

/**
 * Every directory an Openship-managed static route may serve from lives under here
 * (build output at `/opt/openship/static/...`, bare release dirs at
 * `/opt/openship/<project>/...`).
 */
export const MANAGED_STATIC_BASE = "/opt/openship";

/**
 * Validate a doc root before it becomes a public `root` directive.
 *
 * Absolute + no traversal + no injection was NOT enough: it accepted any path on the
 * box, so a wrong value anywhere upstream would have published that directory to the
 * internet ("routing can only go under the project's own output" was the intent, but
 * nothing enforced it). Managed roots are now confined to
 * {@link MANAGED_STATIC_BASE}; only an explicitly adopted root may sit outside it.
 *
 * Confinement is on the PREFIX plus a separator so `/opt/openship-evil` cannot pass
 * as a child of `/opt/openship`.
 */
function assertValidStaticRoot(root: string, opts?: { adopted?: boolean }): void {
  assertNoNginxInjection(root, "static root");
  if (!root.startsWith("/") || root.includes("..")) {
    throw new Error(`Invalid static root (must be an absolute path, no traversal): ${root}`);
  }
  if (opts?.adopted) return;
  const confined = root === MANAGED_STATIC_BASE || root.startsWith(`${MANAGED_STATIC_BASE}/`);
  if (!confined) {
    throw new Error(
      `Refusing to serve static root outside ${MANAGED_STATIC_BASE}: ${root}. ` +
        `Openship-managed routes serve only their own build output; pass ` +
        `staticRootAdopted when importing a root an existing proxy already serves.`,
    );
  }
}

const execFileAsync = promisify(cpExecFile);

/**
 * Turn certbot's verbose failure output into ONE actionable line.
 *
 * certbot buries the cause in a `Type:` / `Detail:` / `Hint:` block and opens with
 * boilerplate ("Saving debug log to …") that tells the operator nothing. Pull the
 * meaningful lines and map the common HTTP-01 failure shapes to a plain-English
 * diagnosis so a failed cert says WHY — DNS, firewall/port-80, or a proxy still on
 * :80 — instead of the opaque opener.
 */
/**
 * Did certbot fail to BIND its challenge listener, rather than fail to validate?
 *
 * One definition, two readers: the diagnosis branch below and the live occupant probe at the
 * issuance call site. Two copies of this regex would drift into a message that names the wrong
 * cause or a probe that runs on the wrong failure.
 *
 * Three wordings because certbot has used all three across versions ("Could not bind TCP port N",
 * "Problem binding to port N", and the bare OS "Address already in use").
 */
export function isAcmePortBindFailure(output: string): boolean {
  return /could not bind (?:tcp )?port|address already in use|problem binding to port/i.test(
    output || "",
  );
}

export function summarizeCertbotFailure(output: string, domain: string): string {
  // certbot never ran: the `docker exec` that would have started it was refused
  // because the edge container is down, and the executor already explained why. No
  // certbot lens applies — and the "last three lines" fallback below would chop that
  // explanation into fragments joined by " · ". Surface it whole.
  const edgeDown = edgeDownExplanation(output);
  if (edgeDown) return edgeDown;

  const structured = certbotDiagnosis(output, domain);
  if (structured) return structured;

  // Nothing structured matched — surface the last non-empty lines (the tail holds
  // the real error) rather than the "Saving debug log" opener.
  //
  // Only sound when certbot ACTUALLY failed: on a zero-exit run the tail is the
  // donation footer, which reads as an error message. Callers that haven't seen a
  // non-zero exit must use {@link certbotDiagnosis} instead.
  const lines = (output || "")
    .split("\n")
    .map((l) => l.trim())
    .filter(Boolean);
  return lines.slice(-3).join(" · ") || `certbot failed to issue a certificate for ${domain}`;
}

/**
 * The structured half of {@link summarizeCertbotFailure}: certbot's own
 * `Detail:` / `Hint:` lines plus a mapped diagnosis, or undefined when the output
 * matches no known failure shape. Never falls back to "the last few lines" — so a
 * caller holding a SUCCESSFUL certbot run can ask "did certbot report a known
 * problem?" without a clean run's footer being dressed up as the cause.
 */
function certbotDiagnosis(output: string, domain: string): string | undefined {
  const text = output || "";
  const pick = (re: RegExp) => text.match(re)?.[0]?.replace(/\s+/g, " ").trim();
  const detail = pick(/Detail:\s*[^\n]+/i);
  const hint = pick(/Hint:\s*[^\n]+/i);

  // Let's Encrypt always REQUESTS `http://<host>/.well-known/acme-challenge/<token>`
  // and follows redirects, so an `https://` URL in the failure means something
  // between the internet and this box redirected the plain-HTTP request — and the
  // answer came from whatever is on :443, not from whatever is on :80. That flips
  // the remediation for an identical 404, so it is read before the branches.
  const challengeUrl = pick(/https?:\/\/\S*\.well-known\/acme-challenge\/\S*/i);
  const redirectedToHttps = /^https:/i.test(challengeUrl ?? "");

  let diagnosis: string | undefined;
  if (isAcmePortBindFailure(text)) {
    // FIRST, and that ordering is the point: this failure happens BEFORE any validation
    // attempt, so every branch below — unreachable :80, DNS, a proxy answering the challenge —
    // would send the operator after something that was never tried. Let's Encrypt was never
    // contacted at all.
    //
    // The bind is the one moving part of our ACME design: issuance is edge-driven (the edge
    // proxies /.well-known/acme-challenge/ to certbot on a fixed loopback port, so there is no
    // port-80 fight and no webroot), and certbot holds that port only for the seconds it is
    // issuing. Nothing else in the design binds it, so a collision means a certbot from an
    // earlier attempt never exited — which is why it is transient and a retry usually clears it.
    //
    // Without this branch the operator got certbot's own wall verbatim: "Saving debug log to
    // /var/log/letsencrypt/letsencrypt.log · Could not bind TCP port 49180 … · Ask for help or
    // search for solutions at https://community.letsencrypt.org" — three lines of which exactly
    // one said anything, and none of it said what to do.
    diagnosis =
      `Couldn't start the certificate challenge listener for ${domain} on port ${ACME_HTTP01_PORT}: ` +
      `something on this server is already holding it. That port is used only while a certificate ` +
      `is being issued, so this is almost always a certificate run from an earlier attempt that ` +
      `hasn't exited — retry, and if it persists find the holder with ` +
      `\`ss -ltnp | grep ${ACME_HTTP01_PORT}\` and stop it. Nothing was requested from ` +
      `Let's Encrypt, so this is not a DNS or routing problem.`;
  } else if (/timeout during connect|connection refused|failed to connect|Timeout/i.test(text)) {
    diagnosis =
      `Port 80 for ${domain} isn't reachable from the internet — a firewall / cloud security group ` +
      `is blocking it, the domain doesn't point at this server, or another proxy is still bound to :80.`;
  } else if (
    /NXDOMAIN|no\s+(A|AAAA)\s+record|DNS problem|could not be resolved|no records? found/i.test(
      text,
    )
  ) {
    diagnosis =
      `${domain} doesn't resolve to this server yet — the DNS A record is missing or hasn't propagated. ` +
      `Wait for propagation, then retry from the Domains tab.`;
  } else if (/\b52[56]\b|ssl handshake failed/i.test(text)) {
    // MUST precede the 40x branch: certbot reports this as "Invalid response from
    // …", which that branch's /invalid response/ would otherwise claim.
    //
    // Matched on the STATUS, not on the word "cloudflare" appearing anywhere in the
    // output — that also fired for certbot's own `--dns-cloudflare` plugin text and
    // for a CF error page carrying any status at all, prescribing SSL/TLS-mode
    // surgery for an unrelated failure. A genuine 40x behind Cloudflare is covered
    // by the redirect branch below, which names CF for the reason it is there.
    //
    // Cloudflare answered the challenge itself instead of forwarding it: its proxy
    // redirected the plain-HTTP request to https ("Always Use HTTPS" / Automatic
    // HTTPS Rewrites / a redirect rule) and then couldn't complete TLS to origin.
    // 525 means it refused our handshake, 526 that it wouldn't accept our
    // certificate — Full (Strict) rejecting the temporary self-signed cert we serve
    // while waiting for this very issuance.
    diagnosis =
      `Cloudflare's proxy is answering the certificate challenge for ${domain} instead of forwarding ` +
      `it to this server: it redirects the request to HTTPS, then rejects the origin's TLS. Fix it one ` +
      `of three ways — set SSL/TLS → Overview to "Full" (not "Full (strict)") until the first ` +
      `certificate is issued, or turn the orange cloud off for this record until it is, or upload a ` +
      `Cloudflare Origin CA certificate from the Domains tab and skip Let's Encrypt entirely.`;
  } else if (/404|invalid response|unauthorized|"?status"?:?\s*40\d/i.test(text)) {
    // Same status, two different causes, told apart by which port answered.
    //
    // Redirected to HTTPS: the request never reached whatever is on :80, so "another
    // web server is still serving :80" is wrong and its remediation — take-over /
    // migrate — would rewrite a working proxy config for a problem it cannot fix.
    // The usual redirector is Cloudflare ("Always Use HTTPS"); since #431 our own
    // :443 catch-all now completes the handshake and answers with the "service not
    // found" page, so this arrives as a 404 where it used to arrive as a 525.
    diagnosis = redirectedToHttps
      ? `The challenge for ${domain} was redirected from HTTP to HTTPS and then answered with a 404 — ` +
        `so whatever served it isn't routing that hostname. If ${domain} is behind Cloudflare, its ` +
        `"Always Use HTTPS" is doing the redirect: set SSL/TLS → Overview to "Full" (not "Full ` +
        `(strict)") until the first certificate is issued, or turn the orange cloud off for this ` +
        `record. Otherwise check the A record points at this server and the domain is registered ` +
        `here. Nothing is occupying :80, so take-over / migrate will not help.`
      : `Port 80 answered but not with our ACME challenge — another web server is still serving :80, so ` +
        `the takeover didn't complete. Re-run and choose take-over / migrate.`;
  } else if (/too many certificates|rateLimited|rate limit/i.test(text)) {
    diagnosis = `Let's Encrypt rate limit reached for ${domain} — wait before retrying.`;
  }

  const parts = [diagnosis, detail, hint].filter(Boolean);
  return parts.length > 0 ? parts.join(" — ") : undefined;
}

