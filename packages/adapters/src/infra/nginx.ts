/**
 * Reverse-proxy headers shared by every proxy_pass location.
 *
 * X-Forwarded-Proto carries `$openship_fwd_proto`, not `$scheme` — see
 * {@link FORWARD_VARS}. Every server block generated by `registerRoute` defines
 * that variable, and these headers are only ever emitted inside those blocks.
 */
const PROXY_HEADERS = `proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $openship_fwd_proto;
        proxy_http_version 1.1;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection "upgrade";`;

/**
 * Per-request vars every generated server block opens with.
 *
 * Both exist because a CDN in front of us may terminate TLS and then reach origin
 * on plain :80 (Cloudflare's "Flexible" SSL mode is the common case):
 *
 *   $openship_redirect_https — an unconditional `301 → https` on :80 sends such a
 *     request back to the CDN, which comes back here on :80: an infinite redirect
 *     loop. Only bounce a request that really arrived over HTTP.
 *   $openship_fwd_proto — overwriting the CDN's X-Forwarded-Proto with `$scheme`
 *     tells the app "http" for a request the browser made over https, which breaks
 *     app-generated absolute URLs, secure cookies, and framework HTTPS guards.
 *
 * Built-in variables only, deliberately: an http-level `map` would have to be
 * shipped in the edge's nginx.conf, and a vhost referencing a variable an
 * already-deployed edge doesn't define fails `openresty -t` — which means the
 * reload is refused and registerRoute rolls the route back. This template has to
 * stay valid on an edge running an older image.
 *
 * Only an EXACT "https" is honoured, and the literal `https` is what gets forwarded
 * — never the client's own string. A chained-proxy header is legally a list
 * ("http, https"), and passing that through verbatim confuses frameworks that
 * compare it to "https"; anything unrecognised falls back to `$scheme`.
 *
 * X-Forwarded-Proto is client-spoofable on a directly-exposed box. All a client
 * gains by lying is skipping its OWN redirect (and telling the app its own request
 * was https) — it can't affect anyone else's traffic, and it could simply have
 * used https to begin with.
 */
const FORWARD_VARS = `    set $openship_fwd_proto $scheme;
    set $openship_redirect_https 1;
    if ($http_x_forwarded_proto = "https") {
        set $openship_fwd_proto https;
        set $openship_redirect_https 0;
    }`;

/** Render extra path-prefix proxy locations (composite single-domain routing). */
function renderProxyLocations(route: RouteConfig): string {
  if (!route.proxyLocations || route.proxyLocations.length === 0) return "";
  return route.proxyLocations
    .map((loc) => {
      assertValidUpstream(loc.targetUrl);
      return `
    location ${loc.pathPrefix} {
        proxy_pass ${loc.targetUrl};
        ${PROXY_HEADERS}
    }`;
    })
    .join("");
}

/**
 * The `location /` body for a route that redirects to another host, or null when
 * it serves normally.
 *
 * `assertValidDomain` runs on the TARGET, not just the route's own domain: the
 * target is interpolated into the emitted config, so an unvalidated one would be
 * a config-injection vector even though it reached us through a validating API.
 * `resolveRedirectStatus` (shared with the API's validator, @repo/core) falls back
 * to 301 rather than emitting `return 0` and making `openresty -t` reject the
 * whole vhost.
 */
function renderHostRedirect(route: RouteConfig): string | null {
  const redirect = route.redirectHost;
  if (!redirect?.target) return null;
  assertValidDomain(redirect.target);
  return `return ${resolveRedirectStatus(redirect.statusCode)} https://${redirect.target}$request_uri;`;
}

/** Render vercel.json `redirects` as `return <code> <dest>` locations. */
function renderRedirects(route: RouteConfig): string {
  if (!route.redirects || route.redirects.length === 0) return "";
  return route.redirects
    .map(
      (r) => `
    location ${r.exact ? "= " : ""}${r.path} {
        return ${r.statusCode} ${r.destination};
    }`,
    )
    .join("");
}

/**
 * Render GLOBAL (source `/(.*)` → path `/`) header rules as server-scope
 * `add_header … always;`. Path-scoped header rules are skipped here (they'd
 * need a dedicated location that could shadow proxy/static behavior) — the
 * common case is global security headers.
 */
function renderServerHeaders(route: RouteConfig): string {
  const global = (route.headerRules ?? []).filter((rule) => rule.path === "/");
  const lines = global.flatMap((rule) =>
    rule.headers.map((h) => `    add_header ${h.key} "${h.value.replace(/"/g, '\\"')}" always;`),
  );
  return lines.length > 0 ? `\n${lines.join("\n")}` : "";
}

/**
 * Render the curated reverse-proxy tunables (client_max_body_size, proxy/body
 * timeouts, buffering, gzip) as server-scope directives. Re-validates every
 * value via `sanitizeProxySettings` before emitting — a malformed value is
 * DROPPED, never interpolated raw into the config (defense-in-depth over the
 * API schema; keeps `nginx -t` safe). gzip emits a FIXED, safe type set.
 */
export function renderProxyOptions(proxy?: ProxySettings | null): string {
  const p = sanitizeProxySettings(proxy);
  if (!p) return "";
  const lines: string[] = [];
  if (p.clientMaxBodySize) lines.push(`    client_max_body_size ${p.clientMaxBodySize};`);
  if (p.proxyReadTimeout) lines.push(`    proxy_read_timeout ${p.proxyReadTimeout};`);
  if (p.proxySendTimeout) lines.push(`    proxy_send_timeout ${p.proxySendTimeout};`);
  if (p.clientBodyTimeout) lines.push(`    client_body_timeout ${p.clientBodyTimeout};`);
  if (p.proxyBuffering !== undefined) {
    lines.push(`    proxy_buffering ${p.proxyBuffering ? "on" : "off"};`);
  }
  if (p.gzip !== undefined) {
    lines.push(`    gzip ${p.gzip ? "on" : "off"};`);
    if (p.gzip) {
      lines.push(`    gzip_types ${PROXY_GZIP_TYPES};`);
      lines.push(`    gzip_min_length 1024;`);
    }
  }
  return lines.length > 0 ? `\n${lines.join("\n")}` : "";
}

