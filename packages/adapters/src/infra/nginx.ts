const GENERATED_HEADER = `# Auto-generated by Openship - do not edit manually\n${GENERATION_MARKER}`;

/**
 * The generation a vhost on disk was written by — `null` when it carries no marker, which
 * means "older than the marker itself" and is therefore always stale.
 *
 * Searched anywhere in the file rather than on line 1: a route with path-scoped response
 * headers gets an http-scope `map` prelude written ABOVE the server block.
 */
export function readVhostGeneration(conf: string): number | null {
  const m = conf.match(/^# openship-vhost-gen: (\d+)$/m);
  return m ? Number(m[1]) : null;
}

/**
 * The plaintext → https upgrade, for the HEAD of a location body in a `:80` block whose
 * domain has a REAL certificate. Guarded by {@link FORWARD_VARS}, so a CDN that already
 * terminated TLS and reached us on :80 is served instead of looped, and `return` inside
 * `if` is the documented-safe use of `if`.
 *
 * Shared by `location /` and by every proxy location in the same block. It has to cover
 * both: a composite `/api/` (or any vercel.json rewrite) that skipped it kept answering
 * in cleartext after the certificate landed — session cookies and Authorization headers
 * on exactly the paths that carry them — while `/` on the same domain upgraded.
 *
 * Only that one block: `$openship_redirect_https` is 1 on :443 as well (nothing there
 * reads it), so emitting this in a shared body would make the TLS block redirect to
 * itself, and a block with no real cert would bounce visitors into a listener that
 * either doesn't exist or presents a self-signed placeholder.
 */
const HTTPS_UPGRADE = `if ($openship_redirect_https) {
            return 301 https://$server_name$request_uri;
        }

        `;

/**
 * Our own webhook-delivery location. Named so {@link renderProxyLocations} can claim it
 * and a generated location can never collide with it.
 */
const WEBHOOK_LOCATION_PREFIX = "/_openship/hooks/";

/**
 * Render extra path-prefix proxy locations (composite single-domain routing, and
 * `vercel.json` rewrites).
 *
 * A rewrite whose destination references the source's wildcard carries a `pattern` +
 * `upstreamPath` and becomes a REGEX location with `rewrite … break`. The capture
 * cannot go into `proxy_pass` directly: any variable there switches nginx to runtime
 * DNS resolution, which needs a `resolver` the edge does not define — so it would fail
 * at request time, not at `nginx -t`. `rewrite … break` rewrites `$uri`, and a
 * `proxy_pass` with no URI part then forwards it, leaving the upstream a literal
 * address resolved once at config load.
 *
 * An `external` target is a third-party origin, so it gets that origin's `Host` and
 * TLS SNI instead of ours — without them a vhost-based or HTTPS origin rejects the
 * request. Internal upstreams (composite services, migration takeover) keep `$host`.
 *
 * The plain-prefix form is `^~`, which is load-bearing: a REGEX location out-ranks
 * every plain prefix however specific, so without it a repo's compiled `/(.*)` rewrite
 * swallowed the composite `/api/` backend — sending authenticated traffic, cookies and
 * all, to whatever origin that vercel.json named. `^~` stops nginx at the prefix and
 * skips the regex phase, the same reason the ACME locations carry it.
 *
 * Each location repeats the redirect chain: nginx runs the rewrite phase of the ONE
 * location it selected, so a redirect that only lived in `location /` would never fire
 * for a path a rewrite also matches — and vercel.json evaluates redirects BEFORE
 * rewrites. `httpsUpgrade` adds {@link HTTPS_UPGRADE} ahead of that chain, for the one
 * block that must bounce plain HTTP.
 *
 * The emitted set is unique BY NAME, built through `claimed`: nginx's duplicate check
 * compares location names and `^~` only sets `noregex`, so a `pathPrefix: "/"` — which a
 * capture-free `vercel.json` rewrite produces, one of Vercel's own documented shapes —
 * sat next to `location /` as `[emerg] duplicate location "/"`. The whole vhost is then
 * refused, and since a routing failure never fails a deploy the domain went dark behind
 * a green deploy. Concatenated sources (a project's composite locations + the compiled
 * ones) can repeat a prefix the same way. `claimed` starts with the names the server
 * block already carries, so those win and the extra is dropped rather than shadowing
 * what serves the site; `/.well-known/` is refused outright instead (see
 * {@link assertNotReservedLocation}) because a location there is a security matter, not
 * a collision. Regex names are namespaced apart, as nginx keeps them.
 */
function renderProxyLocations(route: RouteConfig, opts: { httpsUpgrade: boolean }): string {
  if (!route.proxyLocations || route.proxyLocations.length === 0) return "";
  const head = `${opts.httpsUpgrade ? HTTPS_UPGRADE : ""}${renderRedirectRules(route, "        ")}`;
  const claimed = new Set<string>(["/", WEBHOOK_LOCATION_PREFIX]);
  const blocks: string[] = [];
  for (const loc of route.proxyLocations) {
    assertValidUpstream(loc.targetUrl);
    assertNotReservedLocation(loc.pathPrefix);
    const headers = loc.external ? externalProxyHeaders(loc.targetUrl) : PROXY_HEADERS;
    if (!loc.pattern || !loc.upstreamPath) {
      assertValidLiteralPath(loc.pathPrefix, "proxy location prefix");
      if (claimed.has(loc.pathPrefix)) continue;
      claimed.add(loc.pathPrefix);
      blocks.push(`
    location ^~ ${loc.pathPrefix} {
        ${head}proxy_pass ${loc.targetUrl};
        ${headers}
    }`);
      continue;
    }
    assertValidRedirectPattern(loc.pattern);
    assertNotReservedLocation(loc.pattern);
    assertNoNginxInjection(loc.upstreamPath, "rewrite upstream path");
    // The upstream path is a REQUEST LINE, the most sensitive of the three sinks;
    // only the pattern's own captures may be `$…` there.
    assertNoRuntimeVariable(loc.upstreamPath, "rewrite upstream path", true);
    const match = `^${toNginxPattern(loc.pattern)}$`;
    if (claimed.has(`~ ${match}`)) continue;
    claimed.add(`~ ${match}`);
    blocks.push(`
    location ~ ${match} {
        ${head}rewrite ${match} ${loc.upstreamPath} break;
        proxy_pass ${loc.targetUrl};
        ${headers}
    }`);
  }
  return blocks.join("");
}

/**
 * Refuse a generated location that lives under one of the edge's own `.well-known`
 * prefixes. `^~` protects those only while it is the LONGEST matching prefix, so a
 * `vercel.json` rewrite for `/.well-known/acme-challenge/a` — which `isSafePath`
 * happily admits — out-prefixes it and answers HTTP-01 from an origin the repo names:
 * denial of issuance at best, an attacker-mintable certificate for the operator's
 * domain at worst. The compiler skips these; this is the backstop for a route that
 * arrives from the API or a sidecar instead.
 */
function assertNotReservedLocation(pathOrPattern: string): void {
  // The whole `/.well-known/` namespace, not just the two challenge paths: a prefix
  // SHORTER than a challenge path cannot out-rank its `^~`, but there is no legitimate
  // reason for a project's rule to be in there, and an exact duplicate of a challenge
  // location would itself be an `[emerg] duplicate location`.
  if (pathOrPattern.startsWith(WELL_KNOWN_PREFIX)) {
    throw new Error(
      `Refusing to generate a location under ${WELL_KNOWN_PREFIX}: ${pathOrPattern}. ` +
        `That namespace belongs to the edge — a location there can hijack certificate issuance.`,
    );
  }
}

/** Both challenge locations live under here; see {@link assertNotReservedLocation}. */
const WELL_KNOWN_PREFIX = "/.well-known/";

/**
 * `PROXY_HEADERS` with the origin's own Host, plus TLS SNI. Derived from the one
 * header set rather than restated, so the only difference stays the documented one.
 */
function externalProxyHeaders(targetUrl: string): string {
  const host = new URL(targetUrl).host;
  assertNoNginxInjection(host, "external proxy host");
  return `${PROXY_HEADERS.replace("Host $host;", `Host ${host};`)}
        proxy_ssl_server_name on;`;
}

/**
 * The `location /` body for a route that redirects to another host, or null when
 * it serves normally.
 *
 * `assertValidDomain` runs on the TARGET, not just the route's own domain: the
 * target is interpolated into the emitted config, so an unvalidated one would be
 * a config-injection vector even though it reached us through a validating API.
 * `resolveRedirectStatus` (shared with the API's validator, @repo/core) falls back
 * to 301 rather than emitting `return 0` and making `openresty -t` reject the
 * whole vhost.
 */
function renderHostRedirect(route: RouteConfig): string | null {
  const redirect = route.redirectHost;
  if (!redirect?.target) return null;
  assertValidDomain(redirect.target);
  return `return ${resolveRedirectStatus(redirect.statusCode)} https://${redirect.target}$request_uri;`;
}

/**
 * Render vercel.json `redirects` as a `return`-inside-`if` chain, for interpolation at
 * the HEAD of a location body (never at server scope — that is evaluated before
 * location matching and would shadow the ACME challenge).
 *
 * These were once a location apiece, which nginx cannot express faithfully on four
 * counts — all measured against the pinned OpenResty:
 *
 *  - A wildcard rule needs real captures (`$1..$9` come only from the matching
 *    location's own regex), so it had to be a REGEX location. But a compiled `/(.*)`
 *    whose destination happens to reference NO capture keeps `path: "/"`, and
 *    `location /` was then emitted TWICE — `[emerg] duplicate location "/"`, so the
 *    domain got no vhost at all. That input is one of Vercel's own documented examples.
 *  - A regex location matches `$uri`, which nginx REWRITES internally: `index
 *    index.html` and the `try_files … /index.html` fallback both re-enter location
 *    matching, so `/(.*)\.html` → `/$1` fired on nginx's own `/index.html` and 308'd
 *    every path on the site to `/index`, in a loop.
 *  - A regex location beats every plain prefix regardless of file order, so a later,
 *    broader rule silently out-ranked an earlier, narrower one — the inverse of
 *    vercel.json's first-match-wins.
 *  - `return <code> <dest>` drops the query string.
 *
 * An `if` chain keyed on `$request_uri` fixes all four: the client's raw path never
 * follows an internal rewrite, the chain is evaluated top-down in vercel.json order,
 * `$1..$9` come from the `if`'s own regex, and the query is carried explicitly.
 * `return` inside `if` is the documented-safe use of `if` — the same one this file's
 * `:80` https upgrade and {@link renderUrlShape} already rely on.
 *
 * Captures additionally exclude `?` here (see {@link toNginxPattern}): matched against
 * `$request_uri` a greedy `(.*)` would otherwise swallow the query string into `$1` and
 * then `$is_args$args` would append it a second time.
 */
function renderRedirectRules(route: RouteConfig, indent: string): string {
  if (!route.redirects || route.redirects.length === 0) return "";
  const rules = route.redirects.map((r) => {
    assertValidRedirect(r);
    // A prefix rule needs no end anchor (anything may follow); an exact one and a
    // pattern must not match a longer path, so they anchor past an optional query.
    const match = r.pattern
      ? `^${toNginxPattern(r.pattern, "?")}(?:[?].*)?$`
      : r.exact
        ? `^${escapeLiteralPath(r.path)}(?:[?].*)?$`
        : `^${escapeLiteralPath(r.path)}`;
    // A destination that already carries its own query owns it; otherwise forward the
    // request's, which Vercel preserves and the old `return` form dropped.
    const query = r.destination.includes("?") ? "" : "$is_args$args";
    return `${indent}if ($request_uri ~ "${match}") {
${indent}    return ${r.statusCode} ${r.destination}${query};
${indent}}`;
  });
  return `${rules.join("\n")}\n\n${indent}`;
}

/**
 * A header key + value are interpolated into two nginx COMPLEX values (`add_header` and
 * the path-scoped `map`), where `$name` expands. The compiler refuses a `$` already;
 * this is the backstop for a route arriving from the API or a sidecar, where the cost of
 * missing one is the whole vhost: `"build-$BUILD_ID"` is `[emerg] unknown "build_id"
 * variable`, `"US $5 only"` silently serves `US  only`, and `"$http_cookie"` would
 * reflect request state into the response.
 */
function assertValidHeader(key: string, value: string): void {
  if (!/^[A-Za-z0-9-]+$/.test(key)) throw new Error(`Invalid response header name: ${key}`);
  if (/[\r\n]/.test(value)) throw new Error(`Invalid response header value for ${key}`);
  assertNoRuntimeVariable(value, `response header value for ${key}`);
}

/** An `add_header` line. Values are emitted double-quoted, so quotes are escaped. */
function addHeaderLine(key: string, value: string): string {
  assertValidHeader(key, value);
  return `    add_header ${key} "${value.replace(/"/g, '\\"')}" always;`;
}

/**
 * Render header rules as server-scope `add_header … always;`.
 *
 * A GLOBAL rule (source `/(.*)` → path `/`) emits its value literally. A PATH-scoped
 * rule emits `add_header <key> $var` instead, where `$var` comes from a `map $uri`
 * in the file's prelude — nginx omits an `add_header` whose value evaluates EMPTY, so
 * one server-scope directive covers every path without a dedicated location. That
 * matters because a header-only location would have to duplicate (and could shadow)
 * whatever serves that path, which is why these used to be dropped entirely.
 *
 * INVARIANT: nothing may emit `add_header` INSIDE a location. nginx replaces the
 * whole inherited set when a location declares one of its own, which would silently
 * drop every rule here for that path. Verified against 1.27.5.
 */
function renderServerHeaders(route: RouteConfig, slug: string): string {
  const lines = headerEntries(route, slug).map((e) =>
    e.variable === null
      ? addHeaderLine(e.header.key, e.header.value)
      : `    add_header ${e.header.key} $${e.variable} always;`,
  );
  return lines.length > 0 ? `\n${lines.join("\n")}` : "";
}

/**
 * The flattened `(rule, header)` list, each path-scoped entry paired with the http-scope
 * `map` variable that backs it (`null` for a global rule, which needs no map).
 *
 * The variable name is a MONOTONIC index over this one list — deliberately NOT derived
 * from the path. A map variable is http-wide, and a name built from the path collided in
 * two ordinary cases: `vercel.json` may legitimately carry several `headers` entries for
 * the SAME source, and two different paths squashed alike (`/a-b/` and `/a/b/` both
 * became `_a_b_`). Colliding entries then read one variable, so a real `X-Frame-Options`
 * shipped a sibling rule's value while the other header vanished.
 *
 * What made that silent is that nginx does NOT reject the duplicate: `map` registers its
 * variable as CHANGEABLE, so `openresty -t` succeeds and the LAST declaration wins.
 * (Measured on nginx 1.27.5 and OpenResty 1.27.1.1 — an earlier comment here claimed a
 * duplicate would fail the config test, which is false and was the reason the collision
 * looked harmless.)
 *
 * The slug prefix keeps names unique ACROSS vhosts; `resolveSlug` already guarantees two
 * hosts that slugify alike get distinct slugs, so the pair is globally unique.
 */
function headerEntries(
  route: RouteConfig,
  slug: string,
): Array<{
  rule: RouteHeaderRule;
  header: { key: string; value: string };
  variable: string | null;
}> {
  const prefix = `osh_hdr_${slug.replace(/[^A-Za-z0-9]+/g, "_")}`;
  let n = 0;
  return (route.headerRules ?? []).flatMap((rule) =>
    rule.headers.map((header) => ({
      rule,
      header,
      variable: rule.path === "/" ? null : `${prefix}_${n++}`,
    })),
  );
}

/**
 * The `map` blocks backing path-scoped headers. http scope, so they sit in a prelude
 * ABOVE the server blocks — the vhost files are included at http scope.
 *
 * Keyed on `$request_uri`, NOT `$uri`: `$uri` follows internal rewrites, so a request
 * for `/api/thing` that `try_files` resolves to the SPA `/index.html` is matched as
 * `/index.html` and the rule silently never fires. Verified against 1.27.5 — the header
 * was simply absent. `$request_uri` keeps the client's path (and its query string, which
 * a `^`-anchored prefix match ignores).
 *
 * Variable names come from {@link headerEntries}, which is where their uniqueness — the
 * subtle part — is reasoned about.
 *
 * The path is regex-ESCAPED into the match: it is a literal, but it lands in a regex, so
 * an unescaped `.` made a rule for `/v1.0/` also fire on `/v1x0/`.
 */
function renderHeaderMaps(route: RouteConfig, slug: string): string {
  const scoped = headerEntries(route, slug).filter((e) => e.variable !== null);
  if (scoped.length === 0) return "";
  const blocks = scoped.map((e) => {
    assertValidLiteralPath(e.rule.path, "header rule path");
    assertValidHeader(e.header.key, e.header.value);
    return `map $request_uri $${e.variable} {
    default "";
    ~^${escapeLiteralPath(e.rule.path)} "${e.header.value.replace(/"/g, '\\"')}";
}`;
  });
  return `${blocks.join("\n")}\n`;
}

/**
 * `cleanUrls` / `trailingSlash` redirects, for a STATIC route only — a proxied app's
 * framework owns its own URL shape, and a redirect here would fight it.
 *
 * Emitted INSIDE `location /` and matched on `$request_uri`, which is deliberate on
 * three counts:
 *
 *  - `$request_uri` is what the CLIENT asked for and never changes on an internal
 *    redirect, while `$uri` does. As regex locations keyed on `$uri` these rules fired
 *    on nginx's own rewrites: `index index.html` turned `/docs/` into `/docs/index.html`
 *    and the `.html` rule bounced it to `/docs/index`, and the SPA fallback turned every
 *    404 into a 308 to `/index`. Verified both against 1.27.5.
 *  - `location /` is never reached for `/.well-known/…`, so these cannot shadow an ACME
 *    challenge — which a server-scope `if` (evaluated before location matching) would.
 *  - `$request_uri` is RAW, so percent-encoding survives and no decoded control
 *    character can reach the `Location` header (see {@link CTL}).
 *
 * `return` inside `if` is the documented-safe use of `if`, the same one the `:80`
 * https upgrade in this file already relies on. Dots are written `[.]` rather than
 * `\.` so nothing depends on how nginx unescapes inside a quoted string.
 */
function renderUrlShape(route: RouteConfig): string {
  if (!("staticRoot" in route) || !route.staticRoot) return "";
  const rules: string[] = [];
  // `/about.html` → `/about`, query preserved.
  if (route.cleanUrls) {
    rules.push(`        if ($request_uri ~ "^([^?]*)[.]html([?].*)?$") {
            return 308 $1$2;
        }`);
  }
  if (route.trailingSlash === false) {
    // `/a/` → `/a`. `([^?]+)/` needs a character before the slash, so bare `/` is left
    // alone — redirecting the root to the empty string would be a loop.
    rules.push(`        if ($request_uri ~ "^([^?]+)/([?].*)?$") {
            return 308 $1$2;
        }`);
  }
  // Slash ENFORCEMENT (`trailingSlash: true`) is deliberately NOT an `if` here. As one it
  // redirected before anything checked whether the path resolves, so an extension-less
  // REAL file was unreachable: `/LICENSE` 308'd to `/LICENSE/` and then served the SPA
  // index with a 200 — worse than a 404, because monitoring and crawlers see success.
  // It is now the `try_files` fallback instead ({@link SLASH_FALLBACK}), which by
  // construction only runs once nothing resolved.
  // Interpolated where `location /` is already indented, so the first line drops its own.
  return rules.length > 0 ? `${rules.join("\n").trimStart()}\n\n        ` : "";
}

/** The named location `trailingSlash: true` falls back to — see {@link SLASH_FALLBACK}. */
const SLASH_FALLBACK_NAME = "@osh_add_slash";

/**
 * Where a `trailingSlash: true` static route lands when `try_files` resolved nothing:
 * add the slash if the client's path lacks one, otherwise serve the SPA index.
 *
 * A named location is reached only from `try_files`, so the redirect cannot fire for a
 * path that DID resolve — which is the whole point. The `[^/?]` before the optional query
 * is what makes it loop-free: after `/a` → 308 `/a/` the retry arrives WITH the slash, so
 * the rule declines and the request falls through to the index instead of bouncing again.
 *
 * It repeats `root`: a named location inherits nothing from `location /`, so without it
 * `try_files /index.html` resolves against the SERVER default root and serves OpenResty's
 * stock welcome page instead of the site — measured on 1.27.1.1.
 */
function renderSlashFallback(staticRoot: string): string {
  return `    location ${SLASH_FALLBACK_NAME} {
        root ${staticRoot};

        if ($request_uri ~ "^([^?]*[^/?])([?].*)?$") {
            return 308 $1/$2;
        }

        try_files /index.html =404;
    }`;
}

/**
 * The static `try_files` chain. `$uri.html` is the `cleanUrls` probe (after `$uri`, so a
 * real file still wins).
 *
 * `$uri/` is DROPPED when stripping trailing slashes, and replaced by an explicit
 * `$uri/index.html`. `$uri/` triggers nginx's own 301 directory redirect adding the
 * slash, which the strip rule 308s straight back — an unbreakable loop (`curl -L` exits
 * 47) for any directory the build emits without an index, e.g. a `/blog` holding only
 * `post-1.html`. Probing `$uri/index.html` serves the same directories without ever
 * asking nginx to add a slash we are about to remove.
 *
 * When enforcing the slash, `$uri/` is kept precisely BECAUSE it 301s — that is nginx
 * doing the enforcement for us — and the fallback becomes {@link SLASH_FALLBACK} so a
 * path that resolves to nothing gets the slash while a real file still wins. With
 * `cleanUrls` also set, `$uri.html` resolves `/about` before the fallback is reached, so
 * the pair no longer needs the special case it used to (enforcement being dropped
 * outright) and no longer depends on the build emitting `about/index.html`.
 */
function renderStaticTryFiles(route: RouteConfig): string {
  const parts = ["$uri"];
  if (route.cleanUrls) parts.push("$uri.html");
  if (route.trailingSlash === false) parts.push("$uri/index.html");
  else parts.push("$uri/");
  parts.push(route.trailingSlash === true ? SLASH_FALLBACK_NAME : "/index.html");
  return `try_files ${parts.join(" ")};`;
}

/**
 * Shared body of the two proxy-option renderers below. The set of lines — kinds,
 * scope, version floor, companion defaults — is resolved by `resolveProxyDirectives`
 * in @repo/core, so this function only turns them into text and the live read-back
 * can expect EXACTLY what we write here.
 */
function renderProxyDirectives(
  proxy: ProxySettings | null | undefined,
  opts: { tlsOnly: boolean; nginxVersion?: NginxVersion | null },
): string {
  const lines = resolveProxyDirectives(proxy, {
    scope: opts.tlsOnly ? "tls" : "shared",
    ...(opts.nginxVersion !== undefined ? { nginxVersion: opts.nginxVersion } : {}),
  }).map((d) => `    ${d.directive} ${d.text};`);
  return lines.length > 0 ? `\n${lines.join("\n")}` : "";
}

/**
 * Render the curated reverse-proxy tunables (client_max_body_size, proxy/body
 * timeouts, buffering, gzip, …) as server-scope directives, driven by
 * `PROXY_DIRECTIVES` in @repo/core — the one place the set is declared, so the
 * renderer, the API schema and the config parser cannot drift apart.
 *
 * Re-validates every value via `sanitizeProxySettings` before emitting — a
 * malformed value is DROPPED, never interpolated raw into the config
 * (defense-in-depth over the API schema; keeps `nginx -t` safe). Bool directives
 * render nginx `on`/`off`; gzip's companion lines are fixed literals, never input.
 *
 * TLS-only directives are excluded here and emitted by
 * {@link renderProxyTlsOptions} — this text goes into the :80 block too.
 */
export function renderProxyOptions(
  proxy?: ProxySettings | null,
  nginxVersion?: NginxVersion | null,
): string {
  return renderProxyDirectives(proxy, { tlsOnly: false, nginxVersion });
}

/**
 * The slice of the tunables that belongs ONLY in a `listen 443 ssl` block —
 * currently `http2`, which in a :80 block would enable cleartext h2c instead.
 */
export function renderProxyTlsOptions(
  proxy?: ProxySettings | null,
  nginxVersion?: NginxVersion | null,
): string {
  return renderProxyDirectives(proxy, { tlsOnly: true, nginxVersion });
}

