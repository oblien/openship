// Public test material generated by Chromium's virtual authenticator, never an
// account credential. Keep a real none-attestation and signing key so these
// tests exercise WebAuthn verification rather than mocking its result.
const signingKey = createPrivateKey({
  key: Buffer.from(webauthnFixture.privateKey, "base64"),
  format: "der",
  type: "pkcs8",
});
const digest = (value: string | Buffer) => createHash("sha256").update(value).digest();
function registerCredential(challenge: string, origin = DASHBOARD) {
  const id = randomBytes(32);
  const original = Buffer.from(webauthnFixture.authenticatorData, "base64url");
  const authData = Buffer.from(original);
  digest(new URL(DASHBOARD).hostname).copy(authData);
  // Attested credential data follows the 37-byte authenticator header, the
  // 16-byte AAGUID and a 2-byte length. Preserve its real COSE public key.
  expect(authData.readUInt16BE(53)).toBe(id.length);
  id.copy(authData, 55);
  const attestation = Buffer.from(webauthnFixture.attestationObject, "base64url");
  const offset = attestation.indexOf(original);
  expect(offset).toBeGreaterThan(0);
  authData.copy(attestation, offset);
  return {
    name: "Test security key",
    response: {
      id: id.toString("base64url"),
      rawId: id.toString("base64url"),
      type: "public-key",
      clientExtensionResults: { credProps: { rk: true } },
      response: {
        attestationObject: attestation.toString("base64url"),
        clientDataJSON: Buffer.from(
          JSON.stringify({ type: "webauthn.create", challenge, origin }),
        ).toString("base64url"),
        transports: ["internal"],
      },
    },
  };
}

function authenticateCredential(
  id: string,
  challenge: string,
  options: { origin?: string; rpID?: string; counter?: number } = {},
) {
  const authData = Buffer.alloc(37);
  digest(options.rpID ?? new URL(DASHBOARD).hostname).copy(authData);
  authData[32] = 0x01; // User present, without claiming user verification/MFA.
  authData.writeUInt32BE(options.counter ?? 2, 33);
  const clientData = Buffer.from(
    JSON.stringify({ type: "webauthn.get", challenge, origin: options.origin ?? DASHBOARD }),
  );
  return {
    response: {
      id,
      rawId: id,
      type: "public-key",
      clientExtensionResults: {},
      response: {
        authenticatorData: authData.toString("base64url"),
        clientDataJSON: clientData.toString("base64url"),
        signature: sign(null, Buffer.concat([authData, digest(clientData)]), signingKey).toString(
          "base64url",
        ),
      },
    },
  };
}

function createAuth() {
  return betterAuth({
    baseURL: API,
    secret: SECRET,
    database: drizzleAdapter(connection.db, { provider: "pg", schema }),
    emailAndPassword: { enabled: true, revokeSessionsOnPasswordReset: true },
    trustedOrigins: [DASHBOARD],
    advanced: { cookiePrefix: "security-test" },
    session: {
      additionalFields: {
        activeOrganizationId: { type: "string", defaultValue: "test-org", input: false },
      },
      // Test the same signed-cookie cache used by the SaaS, not just DB sessions.
      cookieCache: { enabled: true },
    },
    socialProviders: {
      google: {
        clientId: "test-google-client",
        clientSecret: "test-google-secret",
        verifyIdToken: async () => true,
        getUserInfo: async () => ({
          user: { id: oauthEmail, email: oauthEmail, name: "Test user", emailVerified: true },
          data: {},
        }),
      },
    },
    plugins: [
      ...accountSecurityPlugins({
        database: connection.db,
        dashboardUrl: DASHBOARD,
        getAuthMode: async () => mode,
      }),
      bearer(),
      emailOTP({
        async sendVerificationOTP({ otp }) {
          emailCode = otp;
        },
      }),
    ],
  });
}
let auth: ReturnType<typeof createAuth>;

class Browser {
  constructor(private readonly instance = auth) {}
  cookies = new Map<string, string>();
  async request(path: string, body?: unknown) {
    const response = await this.instance.handler(
      new Request(`${API}/api/auth${path}`, {
        method: body === undefined ? "GET" : "POST",
        headers: {
          origin: DASHBOARD,
          "content-type": "application/json",
          cookie: [...this.cookies].map(([key, value]) => `${key}=${value}`).join("; "),
        },
        ...(body === undefined ? {} : { body: JSON.stringify(body) }),
      }),
    );
    for (const cookie of response.headers.getSetCookie()) {
      const pair = cookie.split(";")[0]!;
      const index = pair.indexOf("=");
      const key = pair.slice(0, index);
      if (/max-age=0/i.test(cookie)) this.cookies.delete(key);
      else this.cookies.set(key, pair.slice(index + 1));
    }
    const text = await response.text();
    return {
      status: response.status,
      headers: response.headers,
      data: text ? JSON.parse(text) : null,
    };
  }
}

async function account() {
  const email = `security-${crypto.randomUUID()}@example.test`;
  const browser = new Browser();
  const signup = await browser.request("/sign-up/email", {
    name: "Test user",
    email,
    password: PASSWORD,
  });
  expect(signup.status).toBe(200);
  return { email, browser, id: signup.data.user.id as string };
}

async function totp(id: string) {
  const [factor] = await connection.db
    .select()
    .from(schema.twoFactor)
    .where(eq(schema.twoFactor.userId, id));
  const secret = await symmetricDecrypt({ key: SECRET, data: factor!.secret });
  return (await auth.api.generateTOTP({ body: { secret } })).code;
}

async function enroll() {
  const user = await account();
  const enabled = await user.browser.request("/two-factor/enable", { password: PASSWORD });
  expect(enabled.status).toBe(200);
  const verified = await user.browser.request("/two-factor/verify-totp", {
    code: await totp(user.id),
  });
  expect(verified.status).toBe(200);
  return { ...user, codes: enabled.data.backupCodes as string[] };
}

